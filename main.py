data_emp = {
    "Ім'я": ["Олег", "Марія", "Олег", "Іван", "Марія", "Петро", "Іван", "Олег"],
    "Проєкт": ["Альфа", "Бета", "Бета", "Альфа", "Гамма", "Гамма", "Бета", "Альфа"],
    "Години": [40, 35, 20, 25, 30, 45, 15, 10]
}

df_emp = pd.DataFrame(data_emp)

# 1. Виведіть вихідний DataFrame
print("--- Вихідний DataFrame співробітників ---")
print(df_emp)

# 2. Підрахуйте загальну кількість годин кожним співробітником
hours_per_emp = df_emp.groupby("Ім'я")["Години"].sum()
print("\n--- Загальна кількість годин за співробітниками ---")
print(hours_per_emp)

# 3. Підрахуйте загальну кількість годин за кожним проєктом
hours_per_proj = df_emp.groupby("Проєкт")["Години"].sum()
print("\n--- Загальна кількість годин за проєктами ---")
print(hours_per_proj)

# 4. Знайдіть співробітника, який витратив найбільше годин
top_employee = hours_per_emp.idxmax()
top_employee_hours = hours_per_emp.max()
print(f"\nСпівробітник, який витратив найбільше годин: {top_employee} ({top_employee_hours} годин)")